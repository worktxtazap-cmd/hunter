# Шаблоны первого сообщения. {kw} подставляется из заявки.

PARSER = """Привет! По вашему запросу ({kw}) - я как раз этим занимаюсь.

Соберу базу из любого чата или канала: ник, имя, id, а где есть - телефон и почта. Отдам Excel и CSV, дубли и боты вычищу.

1 чат - 200р, 3 чата - 500р, 10 - 1200р. Срок 1-3 часа. Оплата USDT/TON или карта.

Готов начать сегодня. Какой чат интересует?"""


RASSLKA = """Привет! По рассылке ({kw}).

Соберу базу под рассылку: выгрузка участников, чистка от ботов и дублей, сегмент по активности. Отдам Excel и CSV.

1 чат - 200р, 3 чата - 500р, 10 - 1200р. Срок 1-3 часа. Оплата USDT/TON или карта.

Скинуть пример?"""


BOT = """Привет! По вашей заявке ({kw}).

Делаю телеграм-ботов: приём заявок, рассылка, выдача файлов после оплаты, мини-магазин.

Бот под задачу - от 1500р, срок 1-3 дня. Расскажите, что должен делать - накидаю смету."""


DESIGN = """Привет! По вашему запросу ({kw}).

Делаю логотипы, баннеры и креативы для соцсетей. 3 варианта на выбор, правки включены, исходники отдаю.

Логотип - от 500р, баннер - 300р, срок 1-2 дня."""


MAP = [
    ("рассылк", RASSLKA),
    ("нужен бот", BOT),
    ("сделать бота", BOT),
    ("тг бот", BOT),
    ("телеграм бот", BOT),
    ("дизайн", DESIGN),
    ("логотип", DESIGN),
    ("баз", PARSER),
    ("парс", PARSER),
    ("бот", BOT),
]


def pick(keyword, text=""):
    kw = (keyword or "база").lower()
    low = (text or "").lower()
    for key, tpl in MAP:
        if key in kw or key in low:
            return tpl.format(kw=kw)
    return PARSER.format(kw=kw)
